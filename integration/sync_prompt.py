"""Copy prompt v3 from prototype/classifier.py into the package so the package has no dependency on prototype/.

Run from the repo root after any prompt change: python3 integration/sync_prompt.py
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "prototype"))
import classifier as C  # noqa: E402

prompt = C.VERSIONS["v3"]["prompt"]
sha = hashlib.sha256(prompt.encode("utf-8")).hexdigest()[:8]
(ROOT / "integration/optout_classifier/prompt.py").write_text(
    '"""Generated by integration/sync_prompt.py from prototype/classifier.py (VERSIONS["v3"]). Do not edit by hand."""\n'
    "PROMPT_SHA = %s\nSYSTEM_PROMPT = %s\n" % (json.dumps(sha), json.dumps(prompt, ensure_ascii=False)))
print("prompt sha", sha)
